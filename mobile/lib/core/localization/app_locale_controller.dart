class AppLocaleController extends ChangeNotifier {
  AppLocaleController._();

  static final AppLocaleController instance = AppLocaleController._();

  static const _storage = FlutterSecureStorage();
  static const _storageKey = 'preferred_language';

  Locale _locale = const Locale('tr');

  Locale get locale => _locale;
  bool get isTurkish => _locale.languageCode == 'tr';

  Future<void> initialize() async {
    try {
      final savedLanguage = await _storage.read(key: _storageKey);
      _locale = Locale(savedLanguage == 'en' ? 'en' : 'tr');
    } catch (_) {
      _locale = const Locale('tr');
    }
  }

  Future<void> setLanguage(String languageCode) async {
    final normalized = languageCode == 'en' ? 'en' : 'tr';
    if (_locale.languageCode == normalized) return;

    _locale = Locale(normalized);
    notifyListeners();

    try {
      await _storage.write(key: _storageKey, value: normalized);
    } catch (_) {
      // The selected language remains active for the current session.
    }
  }

  String translate(String source) {
    if (isTurkish) return _turkishOverrides[source] ?? source;
    return _english[source] ?? _translateDynamic(source);
  }

  String _translateDynamic(String source) {
    var translated = source;
    for (final entry in _english.entries) {
      if (entry.key.length < 4 || !translated.contains(entry.key)) continue;
      translated = translated.replaceAll(entry.key, entry.value);
    }
    return translated;
  }

